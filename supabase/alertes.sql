CREATE TABLE IF NOT EXISTS public.alertes_prix (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  produit text NOT NULL,
  region text NOT NULL,
  prix_maximum integer CHECK (prix_maximum IS NULL OR prix_maximum > 0),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.alertes_prix ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.alertes_prix TO authenticated;

DROP POLICY IF EXISTS "alertes_select_own" ON public.alertes_prix;
CREATE POLICY "alertes_select_own"
ON public.alertes_prix
FOR SELECT TO authenticated
USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "alertes_insert_own" ON public.alertes_prix;
CREATE POLICY "alertes_insert_own"
ON public.alertes_prix
FOR INSERT TO authenticated
WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "alertes_update_own" ON public.alertes_prix;
CREATE POLICY "alertes_update_own"
ON public.alertes_prix
FOR UPDATE TO authenticated
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "alertes_delete_own" ON public.alertes_prix;
CREATE POLICY "alertes_delete_own"
ON public.alertes_prix
FOR DELETE TO authenticated
USING (auth.uid() = user_id);
