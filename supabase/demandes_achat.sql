CREATE TABLE IF NOT EXISTS public.demandes_achat (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  buyer_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  produit text NOT NULL CHECK (length(trim(produit)) BETWEEN 1 AND 100),
  quantite_kg numeric NOT NULL CHECK (quantite_kg > 0),
  region text NOT NULL CHECK (length(trim(region)) BETWEEN 1 AND 100),
  prix_maximum_kg numeric CHECK (prix_maximum_kg IS NULL OR prix_maximum_kg > 0),
  telephone text NOT NULL CHECK (length(trim(telephone)) BETWEEN 6 AND 25),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.demandes_achat ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON TABLE public.demandes_achat TO anon, authenticated;
GRANT INSERT, DELETE ON TABLE public.demandes_achat TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.demandes_achat_id_seq TO authenticated;

DROP POLICY IF EXISTS "demandes_achat_read_public" ON public.demandes_achat;
CREATE POLICY "demandes_achat_read_public"
ON public.demandes_achat
FOR SELECT TO anon, authenticated
USING (true);

DROP POLICY IF EXISTS "demandes_achat_insert_buyer" ON public.demandes_achat;
CREATE POLICY "demandes_achat_insert_buyer"
ON public.demandes_achat
FOR INSERT TO authenticated
WITH CHECK (
  buyer_id = auth.uid()
  AND EXISTS (
    SELECT 1
    FROM public.profiles
    WHERE profiles.user_id = auth.uid()
      AND profiles.role = 'acheteur'
  )
);

DROP POLICY IF EXISTS "demandes_achat_delete_owner" ON public.demandes_achat;
CREATE POLICY "demandes_achat_delete_owner"
ON public.demandes_achat
FOR DELETE TO authenticated
USING (buyer_id = auth.uid());

DROP POLICY IF EXISTS "demandes_achat_delete_admin" ON public.demandes_achat;
CREATE POLICY "demandes_achat_delete_admin"
ON public.demandes_achat
FOR DELETE TO authenticated
USING (
  EXISTS (
    SELECT 1
    FROM public.profiles
    WHERE profiles.user_id = auth.uid()
      AND profiles.role = 'admin'
  )
);
