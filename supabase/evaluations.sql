CREATE TABLE IF NOT EXISTS public.evaluations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  buyer_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  note smallint NOT NULL CHECK (note BETWEEN 1 AND 5),
  commentaire text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (seller_id, buyer_id),
  CHECK (seller_id <> buyer_id)
);

ALTER TABLE public.evaluations ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON TABLE public.evaluations TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON TABLE public.evaluations TO authenticated;

DROP POLICY IF EXISTS "evaluations_read_public" ON public.evaluations;
CREATE POLICY "evaluations_read_public"
ON public.evaluations
FOR SELECT
TO anon, authenticated
USING (true);

DROP POLICY IF EXISTS "evaluations_insert_buyer" ON public.evaluations;
CREATE POLICY "evaluations_insert_buyer"
ON public.evaluations
FOR INSERT
TO authenticated
WITH CHECK (
  buyer_id = auth.uid()
  AND EXISTS (
    SELECT 1
    FROM public.profiles
    WHERE profiles.user_id = auth.uid()
      AND profiles.role = 'acheteur'
  )
);

DROP POLICY IF EXISTS "evaluations_update_buyer" ON public.evaluations;
CREATE POLICY "evaluations_update_buyer"
ON public.evaluations
FOR UPDATE
TO authenticated
USING (buyer_id = auth.uid())
WITH CHECK (
  buyer_id = auth.uid()
  AND EXISTS (
    SELECT 1
    FROM public.profiles
    WHERE profiles.user_id = auth.uid()
      AND profiles.role = 'acheteur'
  )
);

DROP POLICY IF EXISTS "evaluations_delete_buyer" ON public.evaluations;
CREATE POLICY "evaluations_delete_buyer"
ON public.evaluations
FOR DELETE
TO authenticated
USING (buyer_id = auth.uid());
